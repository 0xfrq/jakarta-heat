lines.append(r"\bottomrule")
lines.append(r"\end{tabularx}")
lines.append(r"\end{table}")
open(os.path.join(BASE,"Tables","tableS9_eligibility.tex"),"w",encoding="utf-8").write("\n".join(lines))
